"""Generate the Secretary backend's copy of the pc_engine tool catalogue.

The Secretary MCP gateway offers the owner's PC (through the PC Control Plus
relay) with exactly the tools, parameters, levels and guidance of
pc_engine.TOOLS. It is TypeScript, so this script writes the catalogue as a
generated module; tests/test_engine.py fails when the file is not what this
script produces now.

Usage: python export_catalogue.py            # rewrite the generated file
       python export_catalogue.py --check    # exit 1 if it is out of date
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

import pc_engine  # noqa: E402

TARGET = Path(__file__).resolve().parents[3] / "backend" / "src" / "modules" / "mcp" / "pcEngineCatalogue.generated.ts"


def catalogue() -> dict:
    return {
        "engine_version": pc_engine.ENGINE_VERSION,
        "tools": [
            {
                "name": spec.name,
                "group": spec.group,
                "level": spec.level,
                "read_only": spec.read_only,
                "destructive": spec.destructive,
                "summary": spec.summary,
                "use_when": spec.use_when,
                "params": [{"name": p.name, "kind": p.kind, "default": p.default, "required": p.required, "description": p.description}
                           for p in spec.params],
            }
            for spec in pc_engine.TOOLS.values()
        ],
        "browser_step_reference": pc_engine.BROWSER_STEP_REFERENCE,
    }


def render() -> str:
    body = json.dumps(catalogue(), indent=2, ensure_ascii=False)
    return (
        "// GENERATED by windows-companion/pc-control/server/export_catalogue.py from pc_engine.TOOLS.\n"
        "// Do not edit: change pc_engine.py, then run the script. tests/test_engine.py checks it.\n"
        "/* eslint-disable */\n"
        "export const PC_ENGINE_CATALOGUE = " + body + " as const;\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is out of date; run python export_catalogue.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET} (engine {pc_engine.ENGINE_VERSION}, {len(pc_engine.TOOLS)} tools)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
