import fs from "node:fs";
import path from "node:path";
import { extractVisiblePhrases } from "./audit-i18n.mjs";

const key = process.env.OPENAI_API_KEY?.trim();
if (!key) throw new Error("OPENAI_API_KEY is required to generate the static UI catalogue.");

const model = process.env.OPENAI_TRANSLATION_MODEL || "gpt-5.4-mini";
const targetDirectory = path.resolve("src/locales/generated");
const cacheFile = path.resolve("scripts/.ui-translation-cache.json");
const targets = {
  "cs-CZ": "Czech (natural Czech business software terminology)",
  "pl-PL": "Polish (natural Polish business software terminology)",
  "fr-FR": "French (natural French business software terminology)",
  "de-DE": "German (natural German business software terminology)",
  "es-ES": "Spanish (natural European Spanish business software terminology)",
  "it-IT": "Italian (natural Italian business software terminology)",
};
const common = [
  "Active", "Inactive", "Archived", "Draft", "Open", "Closed", "Pending", "Completed", "Cancelled",
  "Accepted", "Rejected", "Unknown", "Not set", "Save", "Delete", "Edit", "Create", "Update", "Search",
  "Loading…", "No results", "Yes", "No", "Previous", "Next", "Required", "Optional",
];
const phrases = [...new Set([...extractVisiblePhrases().map(([text]) => text), ...common])].sort((a, b) => a.localeCompare(b));
const cache = fs.existsSync(cacheFile) ? JSON.parse(fs.readFileSync(cacheFile, "utf8")) : {};

function outputText(payload) {
  if (typeof payload.output_text === "string") return payload.output_text;
  return (payload.output || []).flatMap((item) => item.content || []).filter((item) => item.type === "output_text").map((item) => item.text).join("");
}

async function translateBatch(locale, language, batch, attempt = 1) {
  const response = await fetch("https://api.openai.com/v1/responses", {
    method: "POST",
    headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      model,
      store: false,
      reasoning: { effort: "none" },
      max_output_tokens: 12_000,
      instructions: `Translate every array item into ${language}. These are exact fragments from the VCUF Secretary business application. Return exactly one translation per input item in the same order. Preserve punctuation, arrows, ellipses, currency symbols, placeholders, numbers and leading/trailing fragment punctuation. Never translate the product names VCUF, Secretary, Emma or DesignLeaf. Use one language only; never mix Czech and Polish. Keep concise labels concise.`,
      input: JSON.stringify(batch),
      text: {
        format: {
          type: "json_schema",
          name: "ui_translation_batch",
          strict: true,
          schema: {
            type: "object",
            additionalProperties: false,
            required: ["translations"],
            properties: {
              translations: { type: "array", minItems: batch.length, maxItems: batch.length, items: { type: "string" } },
            },
          },
        },
      },
    }),
    signal: AbortSignal.timeout(120_000),
  });
  if (!response.ok) {
    const message = `OpenAI ${response.status}: ${(await response.text()).slice(0, 300)}`;
    if (attempt < 3) return translateBatch(locale, language, batch, attempt + 1);
    throw new Error(message);
  }
  const parsed = JSON.parse(outputText(await response.json()));
  if (!Array.isArray(parsed.translations) || parsed.translations.length !== batch.length) {
    if (attempt < 3) return translateBatch(locale, language, batch, attempt + 1);
    throw new Error(`Translation count mismatch for ${locale}`);
  }
  return parsed.translations;
}

async function translateLocale(locale, language) {
  cache[locale] ||= {};
  const missing = phrases.filter((phrase) => !cache[locale][phrase]);
  const batches = [];
  for (let index = 0; index < missing.length; index += 70) batches.push(missing.slice(index, index + 70));
  for (let index = 0; index < batches.length; index += 3) {
    const group = batches.slice(index, index + 3);
    const translated = await Promise.all(group.map((batch) => translateBatch(locale, language, batch)));
    group.forEach((batch, groupIndex) => batch.forEach((phrase, phraseIndex) => {
      cache[locale][phrase] = translated[groupIndex][phraseIndex];
    }));
    fs.writeFileSync(cacheFile, JSON.stringify(cache, null, 2) + "\n");
    process.stderr.write(`${locale}: ${Math.min(index + group.length, batches.length)}/${batches.length} batches\n`);
  }
}

for (const [locale, language] of Object.entries(targets)) await translateLocale(locale, language);

fs.mkdirSync(targetDirectory, { recursive: true });
for (const locale of Object.keys(targets)) {
  const catalogue = Object.fromEntries(phrases.map((phrase) => [phrase, cache[locale][phrase]]));
  const generated = `// Generated by scripts/generate-ui-translations.mjs. Do not edit by hand.\n` +
    `const catalogue: Record<string, string> = ${JSON.stringify(catalogue, null, 2)};\n\nexport default catalogue;\n`;
  fs.writeFileSync(path.join(targetDirectory, `${locale}.ts`), generated);
}
console.log(`Generated ${Object.keys(targets).length} locale chunks with ${phrases.length} phrases each.`);
